-- ============================================================================
--  ROUTEFLOW: DELIVERY ROUTE OPTIMIZATION SYSTEM (ORACLE DATABASE SCHEMA)
--  Compatible with: Oracle Database 12c, 18c, 19c, 21c, and 23c Free
--  Tables: locations, roads, drivers, vehicles, delivery_trips, trip_stops, road_audit
--  Triggers: trg_roads_insert, trg_roads_update
--  Views: v_active_roads, v_trip_summary
-- ============================================================================

-- 1. LOCATIONS (Graph Nodes)
CREATE TABLE locations (
    location_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR2(100) NOT NULL UNIQUE,
    loc_type     VARCHAR2(20)  DEFAULT 'CUSTOMER' NOT NULL
                 CHECK (loc_type IN ('WAREHOUSE', 'CUSTOMER', 'LANDMARK')),
    created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 2. ROADS (Graph Edges, one row per two-way road with loc_a < loc_b)
CREATE TABLE roads (
    road_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loc_a            NUMBER NOT NULL REFERENCES locations(location_id) ON DELETE CASCADE,
    loc_b            NUMBER NOT NULL REFERENCES locations(location_id) ON DELETE CASCADE,
    distance_km      NUMBER(8,2) NOT NULL CHECK (distance_km > 0),
    travel_time_min  NUMBER(8,2) NOT NULL CHECK (travel_time_min > 0),
    is_active        NUMBER(1)   DEFAULT 1 NOT NULL CHECK (is_active IN (0, 1)),
    CONSTRAINT chk_road_endpoints CHECK (loc_a < loc_b),
    CONSTRAINT unq_road_pair UNIQUE (loc_a, loc_b)
);
CREATE INDEX idx_roads_loc_b ON roads(loc_b);

-- 3. DRIVERS
CREATE TABLE drivers (
    driver_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR2(100) NOT NULL,
    phone      VARCHAR2(20)  NOT NULL UNIQUE CHECK (LENGTH(phone) BETWEEN 7 AND 15)
);

-- 4. VEHICLES
CREATE TABLE vehicles (
    vehicle_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_no        VARCHAR2(30) NOT NULL UNIQUE,
    vehicle_type  VARCHAR2(20) NOT NULL CHECK (vehicle_type IN ('BIKE', 'VAN', 'TRUCK')),
    capacity_kg   NUMBER(8,2)  NOT NULL CHECK (capacity_kg > 0)
);

-- 5. DELIVERY_TRIPS (Planned or completed routes)
CREATE TABLE delivery_trips (
    trip_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id   NUMBER REFERENCES drivers(driver_id)   ON DELETE SET NULL,
    vehicle_id  NUMBER REFERENCES vehicles(vehicle_id) ON DELETE SET NULL,
    depot_id    NUMBER NOT NULL REFERENCES locations(location_id),
    criterion   VARCHAR2(20) NOT NULL CHECK (criterion IN ('DISTANCE', 'TIME')),
    total_km    NUMBER(8,2)  NOT NULL CHECK (total_km >= 0),
    total_min   NUMBER(8,2)  NOT NULL CHECK (total_min >= 0),
    route_text  VARCHAR2(4000) NOT NULL,
    created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX idx_trips_driver ON delivery_trips(driver_id);

-- 6. TRIP_STOPS (Ordered delivery stops of a trip)
CREATE TABLE trip_stops (
    trip_id      NUMBER NOT NULL REFERENCES delivery_trips(trip_id) ON DELETE CASCADE,
    stop_seq     NUMBER(4) NOT NULL CHECK (stop_seq > 0),
    location_id  NUMBER NOT NULL REFERENCES locations(location_id),
    PRIMARY KEY (trip_id, stop_seq)
);

-- 7. ROAD_AUDIT (Populated automatically by Oracle triggers)
CREATE TABLE road_audit (
    audit_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    road_id     NUMBER NOT NULL,
    action      VARCHAR2(20) NOT NULL,
    details     VARCHAR2(255),
    changed_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ============================================================================
-- TRIGGERS
-- ============================================================================
CREATE OR REPLACE TRIGGER trg_roads_insert
AFTER INSERT ON roads
FOR EACH ROW
BEGIN
    INSERT INTO road_audit (road_id, action, details)
    VALUES (:NEW.road_id, 'ADDED',
            TO_CHAR(:NEW.distance_km, 'FM990.0') || ' km, ' || TO_CHAR(:NEW.travel_time_min, 'FM990.0') || ' min');
END;
/

CREATE OR REPLACE TRIGGER trg_roads_update
AFTER UPDATE OF distance_km, travel_time_min, is_active ON roads
FOR EACH ROW
BEGIN
    INSERT INTO road_audit (road_id, action, details)
    VALUES (:NEW.road_id,
            CASE WHEN :OLD.is_active = 1 AND :NEW.is_active = 0 THEN 'CLOSED'
                 WHEN :OLD.is_active = 0 AND :NEW.is_active = 1 THEN 'REOPENED'
                 ELSE 'UPDATED' END,
            TO_CHAR(:NEW.distance_km, 'FM990.0') || ' km, ' || TO_CHAR(:NEW.travel_time_min, 'FM990.0') || ' min');
END;
/

-- ============================================================================
-- VIEWS
-- ============================================================================
CREATE OR REPLACE VIEW v_active_roads AS
SELECT r.road_id,
       a.name AS from_location,
       b.name AS to_location,
       r.distance_km,
       r.travel_time_min,
       r.is_active
FROM   roads r
JOIN   locations a ON a.location_id = r.loc_a
JOIN   locations b ON b.location_id = r.loc_b;

CREATE OR REPLACE VIEW v_trip_summary AS
SELECT t.trip_id,
       TO_CHAR(t.created_at, 'YYYY-MM-DD HH24:MI') AS created_at,
       l.name                                      AS depot,
       NVL(d.name, 'Unassigned')                   AS driver,
       NVL(v.reg_no, '-')                          AS vehicle,
       t.criterion,
       (SELECT COUNT(*) FROM trip_stops s WHERE s.trip_id = t.trip_id) AS stops,
       ROUND(t.total_km, 1)                        AS total_km,
       ROUND(t.total_min, 1)                       AS total_min,
       t.route_text
FROM   delivery_trips t
JOIN   locations l      ON l.location_id = t.depot_id
LEFT JOIN drivers d     ON d.driver_id   = t.driver_id
LEFT JOIN vehicles v    ON v.vehicle_id  = t.vehicle_id;
